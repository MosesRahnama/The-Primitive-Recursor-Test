def section(title: str, text: str, cols: list[str], headers: list[str], body: list[list[object]], denom: str) -> dict:
    return {"title": title, "text": text, "cols": cols, "headers": headers, "body": body, "denom": denom}


def render(title: str, intro: str, secs: list[dict]) -> str:
    lines = [MARKER, "", f"# {title}", "", intro, ""]
    for s in secs:
        lines += [f"## {s['title']}", "", f"> _{s['text']}_", ""]
        for c in s["cols"]:
            lines.append(f"- `{c}`: {desc(c)}")
        lines += ["", f"Denominator: {s['denom']}", ""]
        lines += table(s["headers"], s["body"]) if s["body"] else ["No applicable rows."]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write(path: Path, text: str) -> Path:
    # Every generated report carries its input generation and digest on line 2.
    if text.startswith(MARKER):
        text = text.replace(MARKER, MARKER + "\n" + provenance(), 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


