def basis_digest() -> str:
    """SHA-256 over the basis-of-record consolidation CSVs, name and bytes, sorted."""
    if "v" not in _DIGEST:
        h = hashlib.sha256()
        for p in sorted(FINAL_DIR.glob("final_*_consolidation.csv")):
            h.update(p.name.encode("utf-8"))
            h.update(p.read_bytes())
        _DIGEST["v"] = h.hexdigest()
    return _DIGEST["v"]


def provenance() -> str:
    return f"<!-- BASIS OF RECORD: {FINAL_DIR.name} | sha256 {basis_digest()} -->"


