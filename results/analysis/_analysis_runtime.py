def gammaincc(a: float, x: float) -> float:
    if x <= 0:
        return 1.0
    if x < a + 1.0:
        ap = a
        summ = 1.0 / a
        delta = summ
        for _ in range(200):
            ap += 1.0
            delta *= x / ap
            summ += delta
            if abs(delta) < abs(summ) * 1e-14:
                break
        return max(0.0, min(1.0, 1.0 - summ * math.exp(-x + a * math.log(x) - math.lgamma(a))))
    b = x + 1.0 - a
    c = 1.0 / 1e-300
    d = 1.0 / b
    h = d
    for i in range(1, 200):
        an = -i * (i - a)
        b += 2.0
        d = an * d + b
        if abs(d) < 1e-300:
            d = 1e-300
        c = b + an / c
        if abs(c) < 1e-300:
            c = 1e-300
        d = 1.0 / d
        delta = d * c
        h *= delta
        if abs(delta - 1.0) < 1e-14:
            break
    return max(0.0, min(1.0, math.exp(-x + a * math.log(x) - math.lgamma(a)) * h))


def chi_square_independence(rs: list[dict[str, str]], group_col: str, outcome_col: str) -> tuple[float, int, float]:
    groups = sorted({disp(r.get(group_col)) for r in rs})
    outs = sorted({disp(r.get(outcome_col)) for r in rs})
    table_counts = [[sum(1 for r in rs if disp(r.get(group_col)) == g and disp(r.get(outcome_col)) == o) for o in outs] for g in groups]
    row_tot = [sum(row) for row in table_counts]
    col_tot = [sum(table_counts[i][j] for i in range(len(groups))) for j in range(len(outs))]
    n = sum(row_tot)
    stat = 0.0
    for i, row in enumerate(table_counts):
        for j, obs in enumerate(row):
            exp = row_tot[i] * col_tot[j] / n if n else 0.0
            if exp:
                stat += (obs - exp) ** 2 / exp
    dof = max(0, (len(groups) - 1) * (len(outs) - 1))
    p = gammaincc(dof / 2.0, stat / 2.0) if dof else 1.0
    return stat, dof, p


def fisher_exact_from_pred(rs: list[dict[str, str]], pred, outcome) -> tuple[int, int, int, int, float, float]:
    a = sum(1 for r in rs if pred(r) and outcome(r))
    b = sum(1 for r in rs if pred(r) and not outcome(r))
    c = sum(1 for r in rs if not pred(r) and outcome(r))
    d = sum(1 for r in rs if not pred(r) and not outcome(r))
    if b * c:
        odds = (a * d) / (b * c)
    elif a * d:
        odds = math.inf
    else:
        odds = 0.0
    row1 = a + b; row2 = c + d; col1 = a + c; n = row1 + row2
    lo = max(0, col1 - row2); hi = min(row1, col1)
    denom = math.comb(n, row1)
    def prob(x: int) -> float:
        return math.comb(col1, x) * math.comb(n - col1, row1 - x) / denom
    obs = prob(a)
    p = sum(prob(x) for x in range(lo, hi + 1) if prob(x) <= obs + 1e-15)
    return a, b, c, d, odds, min(1.0, p)


def odds_fmt(v: float) -> str:
    if math.isinf(v):
        return "inf"
    if v == 0:
        return "0"
    if abs(v) < 0.01 or abs(v) >= 1000:
        return f"{v:.3e}"
    return f"{v:.4g}"


def p_fmt(v: float) -> str:
    return f"{v:.3e}" if v < 0.001 else f"{v:.4f}"


