def yn(v: bool) -> str:
    return "yes" if v else "no"


def rate_count(rs: list[dict[str, str]], pred) -> tuple[int, str, float]:
    n = sum(1 for r in rs if pred(r))
    rate = 100 * n / len(rs) if rs else 0.0
    return n, f"{n}/{len(rs)} ({pct(n, len(rs))})", rate


def delta_pts(a: float, b: float) -> str:
    return f"{b - a:+.1f} pts"


def mean_numeric(rs: list[dict[str, str]], col: str) -> float:
    vals = []
    for r in rs:
        try:
            vals.append(float(r.get(col, "")))
        except ValueError:
            pass
    return sum(vals) / len(vals) if vals else 0.0


def by_model(rs: list[dict[str, str]]) -> dict[str, list[dict[str, str]]]:
    out = defaultdict(list)
    for r in rs:
        out[disp(r.get("model"))].append(r)
    return out


def model_delta_rows(left: list[dict[str, str]], right: list[dict[str, str]], metrics: list[tuple[str, str, str]]) -> tuple[list[list[object]], list[list[object]]]:
    left_m = by_model(left); right_m = by_model(right)
    rows_out = []
    direction = Counter()
    paired_models = 0
    for m in sorted(set(left_m) | set(right_m)):
        row = [m, len(left_m.get(m, [])), len(right_m.get(m, []))]
        changed = False
        paired = bool(left_m.get(m)) and bool(right_m.get(m))
        if paired:
            paired_models += 1
        for label_name, col, kind in metrics:
            lr = left_m.get(m, []); rr = right_m.get(m, [])
            if kind == "correct":
                _, lcell, lrate = rate_count(lr, lambda r, c=col: is_correct(r.get(c)))
                _, rcell, rrate = rate_count(rr, lambda r, c=col: is_correct(r.get(c)))
            elif kind == "yes":
                _, lcell, lrate = rate_count(lr, lambda r, c=col: is_yes(r.get(c)) or low(r.get(c)) == "yes")
                _, rcell, rrate = rate_count(rr, lambda r, c=col: is_yes(r.get(c)) or low(r.get(c)) == "yes")
            else:
                _, lcell, lrate = rate_count(lr, col)
                _, rcell, rrate = rate_count(rr, col)
            if not paired:
                row += [lcell, rcell, "n/a"]
                continue
            if abs(rrate - lrate) > 1e-9:
                changed = True
            direction[(label_name, "control higher" if rrate > lrate else "control lower" if rrate < lrate else "same")] += 1
            row += [lcell, rcell, delta_pts(lrate, rrate)]
        row.append(yn(changed) if paired else "not paired")
        rows_out.append(row)
    dir_rows = [[metric, status, n, pct(n, paired_models)] for (metric, status), n in sorted(direction.items())]
    if paired_models != len(rows_out):
        dir_rows.append(["pairing coverage", "paired models", paired_models, pct(paired_models, len(rows_out))])
    return rows_out, dir_rows


