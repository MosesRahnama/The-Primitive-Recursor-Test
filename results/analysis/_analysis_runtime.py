def table(headers: list[str], body: list[list[object]]) -> list[str]:
    def e(x): return str(x).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(e(x) for x in headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(e(x) for x in row) + " |" for row in body]
    return out


def counts(rs: list[dict[str, str]], col: str, limit: int | None = None) -> list[list[object]]:
    c = Counter(disp(r.get(col)) for r in rs)
    items = sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))
    if limit:
        items = items[:limit]
    return [[k, v, pct(v, len(rs))] for k, v in items]


def ncorrect(rs: list[dict[str, str]], col: str) -> int:
    return sum(1 for r in rs if is_correct(r.get(col)))


def nvalue(rs: list[dict[str, str]], col: str, value: str) -> int:
    return sum(1 for r in rs if low(r.get(col)) == low(value))


def npred(rs: list[dict[str, str]], pred) -> int:
    return sum(1 for r in rs if pred(r))


def metric_row(name: str, n: int, d: int) -> list[object]:
    return [name, f"{n}/{d}", pct(n, d)]


def median(xs: list[float]) -> float:
    if not xs:
        return 0.0
    ys = sorted(xs)
    mid = len(ys) // 2
    return ys[mid] if len(ys) % 2 else (ys[mid - 1] + ys[mid]) / 2


def crosstab(rs: list[dict[str, str]], a: str, b: str, limit: int = 50) -> list[list[object]]:
    c = Counter((disp(r.get(a)), disp(r.get(b))) for r in rs)
    return [[x, y, n, pct(n, len(rs))] for (x, y), n in sorted(c.items(), key=lambda kv: (-kv[1], kv[0][0], kv[0][1]))[:limit]]


def group_rates(rs: list[dict[str, str]], group: str, metrics: list[str]) -> list[list[object]]:
    g = defaultdict(list)
    for r in rs:
        g[disp(r.get(group))].append(r)
    out = []
    for key, gr in sorted(g.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        out.append([key, len(gr)] + [f"{ncorrect(gr, m)}/{len(gr)} ({pct(ncorrect(gr, m), len(gr))})" for m in metrics if m in gr[0]])
    return out


def ordered_unique(values: list[str]) -> list[str]:
    out = []
    seen = set()
    for v in values:
        x = disp(v)
        if x not in seen:
            seen.add(x)
            out.append(x)
    return out


def stability_specs(slug: str, rs: list[dict[str, str]]) -> list[tuple[str, str]]:
    c = TESTS[slug]
    available = set(rs[0]) if rs else set()
    specs: list[tuple[str, str]] = []

    def add(group: str, col: str) -> None:
        if col and col in available and col not in {c for _, c in specs}:
            specs.append((group, col))

    for col in c.get("verdicts", []):
        add("verdict", col)
    for col in c.get("scores", []):
        add("score", col)
    for col in c.get("methods", []):
        add("method", col)
    for col in c.get("boundary", []):
        add("boundary", col)
    for col in c.get("evidence", []):
        add("evidence/localization", col)
    for col in c.get("control", []):
        add("control/pair", col)

    if slug.startswith("schema-b"):
        add("method-vector", "derived_accepted_method_set")
        add("method-vector", "derived_terminates_vector")
        add("method-vector", "derived_boundary_vector")
        for x in "ABCDE":
            add("score", f"derived_method_{x}_fully_correct")
            add("method-vector", f"derived_method_{x}_yes_yes_accepted")
    if slug in {"schema-a", "schema-a-new-system"}:
        add("verdict", "turn2_original_question_restated_verdict")
        add("method", "turn2_primary_method")
        add("boundary", "turn2_q3_outside_boundary")
    if slug == "test-01":
        add("control/pair", "prompt_variant")
        add("method", "answer_mode_primary_method")
    return specs


def model_groups(rs: list[dict[str, str]]) -> dict[str, list[dict[str, str]]]:
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rs:
        groups[disp(r.get("model"))].append(r)
    return dict(sorted(groups.items(), key=lambda kv: kv[0]))


def distinct_for(gr: list[dict[str, str]], col: str) -> list[str]:
    return ordered_unique([r.get(col, "") for r in gr])


def correctness_cell(gr: list[dict[str, str]], col: str) -> str:
    return f"{ncorrect(gr, col)}/{len(gr)} ({pct(ncorrect(gr, col), len(gr))})" if gr else "0/0 (n/a)"


