def validation_rows() -> list[list[str]]:
    out = []
    missing_cols = []
    for slug in TESTS:
        valid = set(header(slug))
        valid.update({"derived_w_layer", "derived_yes_with_inadequate_method", "derived_yes_with_boundary_external_method", "derived_yes_with_correct_admissible_method", "derived_accepted_method_set", "derived_terminates_vector", "derived_boundary_vector"})
        valid.update({f"derived_method_{x}_fully_correct" for x in "ABCDE"})
        valid.update({f"derived_method_{x}_yes_yes_accepted" for x in "ABCDE"})
        for report in cfg_reports(slug):
            for sec in report_sections(slug, report):
                for col in sec["cols"]:
                    if col and col not in valid:
                        missing_cols.append(f"{slug}:{report}:{col}")
    out.append(["per-test report columns exist in scored CSVs or derived fields", "pass" if not missing_cols else "fail", "; ".join(missing_cols[:8])])
    py = sorted(ANALYSIS_DIR.rglob("*.py"))
    missing = [str(p.relative_to(ANALYSIS_DIR)) for p in py if not p.with_suffix(".md").exists()]
    out.append(["every python file has same-stem markdown", "pass" if not missing else "fail", "; ".join(missing[:8])])
    nong = []
    for p in ANALYSIS_DIR.rglob("*.md"):
        text = p.read_text(encoding="utf-8", errors="ignore")
        if MARKER not in text and "HAND-AUTHORED" not in text[:200]:
            nong.append(str(p.relative_to(ANALYSIS_DIR)))
    out.append(["every analysis markdown has generated marker or is marked hand-authored", "pass" if not nong else "fail", "; ".join(nong[:8])])
    miss_sum = [s for s in TESTS if not (ANALYSIS_DIR / s / f"{s}-statistical_summary.md").exists()]
    out.append(["per-folder statistical summaries exist", "pass" if not miss_sum else "fail", "; ".join(miss_sum)])
    miss_schema = [s for s in TESTS if not (SCHEMA_DIR / f"{s}_MASTER_SCHEMA.md").exists()]
    out.append(["master schemas exist", "pass" if not miss_schema else "fail", "; ".join(miss_schema)])
    root = ANALYSIS_DIR / "all_tests_statistics.md"
    out.append(["root all_tests_statistics.md exists", "pass" if root.exists() else "fail", str(root.relative_to(ROOT))])
